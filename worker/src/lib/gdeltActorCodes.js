export function decodeActor(actorCode) {
  if (!actorCode) return null;

  const chunks = actorCode.match(/.{1,3}/g) || [];
  let countryName = null;
  const roles = [];
  const unrecognized = [];

  for (const chunk of chunks) {
    if (!countryName && ACTOR_COUNTRY_NAMES[chunk]) {
      countryName = ACTOR_COUNTRY_NAMES[chunk];
    } else if (ACTOR_TYPE_LABELS[chunk]) {
      roles.push(ACTOR_TYPE_LABELS[chunk]);
    } else {
      unrecognized.push(chunk);
    }
  }

  if (!countryName && roles.length === 0) {
    return { code: actorCode, label: actorCode };
  }

  const parts = [countryName, ...roles].filter(Boolean);
  if (unrecognized.length > 0) parts.push(unrecognized.join(""));

  return {
    code: actorCode,
    label: parts.join(" — "),
    country: countryName,
    roles,
  };
}
