function normalizeCountryKey(value = "") {
  return value
    .toString()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// returns an array of FIPS codes for a country name or topic key
export function getFipsCodes(countryOrTopic) {
  const normalized = normalizeCountryKey(countryOrTopic);
  const aliases = countryKeywords.aliases || {};
  const resolvedKey = aliases[normalized] || normalized;

  const match = FIPS_BY_COUNTRY[normalized] || FIPS_BY_COUNTRY[resolvedKey];
  if (!match) return [];
  return Array.isArray(match) ? match : [match];
}

// track relevant FIPS codes
export function getAllTrackedFipsCodes() {
  const codes = new Set();
  for (const value of Object.values(FIPS_BY_COUNTRY)) {
    if (Array.isArray(value)) {
      value.forEach((code) => codes.add(code));
    } else {
      codes.add(value);
    }
  }
  return codes;
}
